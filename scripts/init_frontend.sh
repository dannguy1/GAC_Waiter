#!/bin/bash
# scripts/init_frontend.sh
# Manually initializes Next.js + Tailwind + Typescript frontend

# Set Path
export PATH=$(pwd)/tools/node-v20.11.0-linux-x64/bin:$PATH

echo "Initializing Frontend in ./frontend..."
mkdir -p frontend
cd frontend

# 1. Initialize Package.json
if [ ! -f package.json ]; then
    npm init -y
fi

# 2. Install Dependencies
echo "Installing Core Dependencies..."
npm install next react react-dom lucide-react axios class-variance-authority clsx tailwind-merge framer-motion zustand

echo "Installing Dev Dependencies..."
npm install -D typescript @types/node @types/react @types/react-dom autoprefixer postcss tailwindcss eslint eslint-config-next

# 3. Create TSConfig (Minimal to start, Next.js will auto-fix)
cat > tsconfig.json <<EOF
{
  "compilerOptions": {
    "target": "es5",
    "lib": ["dom", "dom.iterable", "esnext"],
    "allowJs": true,
    "skipLibCheck": true,
    "strict": true,
    "forceConsistentCasingInFileNames": true,
    "noEmit": true,
    "esModuleInterop": true,
    "module": "esnext",
    "moduleResolution": "node",
    "resolveJsonModule": true,
    "isolatedModules": true,
    "jsx": "preserve",
    "incremental": true,
    "plugins": [
      {
        "name": "next"
      }
    ],
    "paths": {
      "@/*": ["./src/*"]
    }
  },
  "include": ["next-env.d.ts", "**/*.ts", "**/*.tsx", ".next/types/**/*.ts"],
  "exclude": ["node_modules"]
}
EOF

# 4. Tailwind Config
cat > tailwind.config.ts <<EOF
