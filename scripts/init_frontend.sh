EOF

# 5. PostCSS Config
cat > postcss.config.js <<EOF
module.exports = {
  plugins: {
    tailwindcss: {},
    autoprefixer: {},
  },
}
EOF

# 6. Next Config
cat > next.config.js <<EOF
/** @type {import('next').NextConfig} */
